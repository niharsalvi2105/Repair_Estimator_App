import { test, expect } from '@playwright/test'

for (const language of ['en', 'fr']) {
  for (const width of [320, 1366]) {
    test(`material catalog preview supports both scopes and market conversion at ${width}px ${language}`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 })
      const writes = []
      page.on('request', (request) => {
        if (['POST', 'PATCH', 'PUT', 'DELETE'].includes(request.method())) writes.push(request.url())
      })
      await page.goto('/?materialPreview=1')
      await expect(page.getByRole('heading', { level: 1 })).toHaveText('Spare-parts material preview')
      await page.getByLabel('Interface language').selectOption(language)
      const fr = language === 'fr'
      const label = (en, french) => fr ? french : en
      await page.getByLabel(label('Market', 'Marché')).selectOption('CKE')
      const packageSection = page.locator('[data-scope=package]')
      await packageSection.getByRole('button', { name: label('Add material', 'Ajouter un matériau'), exact: true }).click()
      const first = packageSection.locator('fieldset')
      await first.getByLabel(label('Catalog part', 'Pièce du catalogue')).selectOption('demo-kone-1')
      await expect(first.locator('[data-value=unit-cost]')).toHaveText(fr ? '172,20 CAD' : '172.20 CAD')
      await expect(first.locator('[data-value=selling]')).toHaveText(fr ? '350,00 CAD' : '350.00 CAD')
      const cost = await first.locator('[data-value=total-cost]').textContent()
      await first.getByLabel(label('KONE markup (%)', 'Majoration KONE (%)'), { exact: true }).fill('20')
      await expect(first.locator('[data-value=selling]')).toHaveText(fr ? '378,00 CAD' : '378.00 CAD')
      await expect(first.locator('[data-value=total-cost]')).toHaveText(cost)
      await first.getByLabel(label('KONE markup (%)', 'Majoration KONE (%)'), { exact: true }).fill('101')
      await expect(first.getByRole('alert')).toContainText('100')
      await expect(page.locator('[data-total=combined]')).toHaveCount(0)
      await first.getByLabel(label('KONE markup (%)', 'Majoration KONE (%)'), { exact: true }).fill('10')
      await first.getByLabel(label('Search part number or description', 'Rechercher un numéro ou une description')).fill('not-found')
      await expect(first.getByRole('status')).toBeVisible()
      await expect(first.locator('[data-value=unit-cost]')).toHaveText(fr ? '172,20 CAD' : '172.20 CAD')
      await first.getByLabel(label('Search part number or description', 'Rechercher un numéro ou une description')).fill('precision')
      await first.getByLabel(label('Catalog part', 'Pièce du catalogue')).selectOption('demo-kone-2')
      await expect(first.locator('[data-value=unit-cost]')).toHaveText(fr ? '7,73178 CAD' : '7.73178 CAD')
      await first.getByLabel(label('Search part number or description', 'Rechercher un numéro ou une description')).fill('')
      await first.getByLabel(label('Catalog part', 'Pièce du catalogue')).selectOption('demo-kone-1')
      const additional = page.locator('[data-scope=additional]')
      await additional.getByRole('button', { name: label('Add material', 'Ajouter un matériau'), exact: true }).click()
      const second = additional.locator('fieldset')
      await second.getByLabel(label('Part type', 'Type de pièce')).selectOption('non-kone')
      await expect(second.getByLabel(label('KONE markup (%)', 'Majoration KONE (%)'), { exact: true })).toHaveCount(0)
      await second.getByLabel(label('Catalog part', 'Pièce du catalogue')).selectOption('demo-non-kone-1')
      await expect(second.locator('[data-value=unit-cost]')).toHaveText(fr ? '17,22 CAD' : '17.22 CAD')
      await second.getByLabel(label('Entry source', 'Source de saisie')).selectOption('manual')
      await second.getByLabel(label('Part number', 'Numéro de pièce'), { exact: true }).fill('CUSTOM-42')
      await second.getByLabel('Description', { exact: true }).fill('Manual non-KONE bracket')
      await second.getByLabel(new RegExp(label('Unit cost', 'Coût unitaire'))).fill('10')
      await expect(second.locator('[data-value=unit-cost]')).toHaveText(fr ? '10,00 CAD' : '10.00 CAD')
      await expect(page.locator('[data-total=package]')).toHaveText(fr ? '204,92 CAD' : '204.92 CAD')
      await expect(page.locator('[data-total=additional]')).toHaveText(fr ? '11,90 CAD' : '11.90 CAD')
      await expect(page.locator('[data-total=combined]')).toHaveText(fr ? '216,82 CAD' : '216.82 CAD')
      await expect(page.locator('[data-total=selling]')).toHaveText(fr ? '350,00 CAD' : '350.00 CAD')
      await page.getByLabel(new RegExp(label('Separate manual additional amount', 'Montant supplémentaire manuel distinct'))).fill('5')
      await expect(page.locator('[data-total=combined]')).toHaveText(fr ? '222,77 CAD' : '222.77 CAD')
      await page.getByLabel(label('Market', 'Marché')).selectOption('CKQ')
      await expect(first.locator('[data-value=unit-cost]')).toHaveText(fr ? '172,20 CAD' : '172.20 CAD')
      await expect(second.getByLabel(new RegExp(label('Unit cost', 'Coût unitaire')))).toHaveValue('')
      await second.getByLabel(new RegExp(label('Unit cost', 'Coût unitaire'))).fill('10')
      await page.getByLabel(label('Market', 'Marché')).selectOption('MKO')
      await expect(first.locator('[data-value=unit-cost]')).toHaveText(fr ? '100,00 USD' : '100.00 USD')
      await expect(first.locator('[data-value=selling]')).toHaveText(fr ? '250,00 USD' : '250.00 USD')
      await second.getByRole('button', { name: label('Remove material', 'Supprimer le matériau') }).click()
      await expect(page.locator('[data-total=additional]')).toHaveText(fr ? '0,00 USD' : '0.00 USD')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
      await expect(page.getByRole('button', { name: /save|enregistrer/i })).toHaveCount(0)
      expect(writes).toEqual([])
      await page.reload()
      await expect(page.locator('.material-preview-line')).toHaveCount(0)
    })
  }
}
